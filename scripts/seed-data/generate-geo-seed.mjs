import { readFileSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));

const csv = readFileSync(join(__dirname, 'cuba-municipalities.csv'), 'utf-8');

const lines = csv.split('\n').filter(Boolean);
const [, ...rows] = lines;

const provinces = [...new Set(rows.map(r => r.split(',')[0]))];

const countryCode = 'CU';
const countryName = 'Cuba';

function esc(val) {
  return `'${val.replace(/'/g, "''")}'`;
}

function latLng(province) {
  const coords = {
    'Pinar del Río': [22.412, -83.696],
    'Artemisa': [22.813, -82.762],
    'La Habana': [23.113, -82.366],
    'Mayabeque': [22.968, -82.151],
    'Matanzas': [23.041, -81.577],
    'Cienfuegos': [22.146, -80.436],
    'Villa Clara': [22.407, -79.965],
    'Sancti Spíritus': [21.930, -79.443],
    'Ciego de Ávila': [21.840, -78.762],
    'Camagüey': [21.381, -77.907],
    'Las Tunas': [20.960, -76.951],
    'Holguín': [20.887, -76.263],
    'Granma': [20.379, -76.643],
    'Santiago de Cuba': [20.020, -75.829],
    'Guantánamo': [20.144, -75.209],
    'Isla de la Juventud': [21.748, -82.762],
  };
  return coords[province] || [21.5, -80.0];
}

function municipalityCoords(name, province) {
  const known = {
    'Pinar del Río': { 'Pinar del Río': [22.417, -83.698] },
    'La Habana': { 'La Habana': [23.113, -82.366] },
    'Isla de la Juventud': { 'Isla de la Juventud': [21.748, -82.762] },
  };
  return known[province]?.[name] || null;
}

function geoInsert(level, name, parentSubselect, lat, lng) {
  const latPart = lat != null ? lat : 'NULL';
  const lngPart = lng != null ? lng : 'NULL';
  return `SELECT ${esc(countryCode)}, ${esc(level)}, ${esc(name)}, ${parentSubselect}, ${latPart}, ${lngPart}, TRUE`;
}

let sql = `-- Generated by generate-geo-seed.mjs
-- V21: Geo regions (Cuba)

INSERT INTO geo_regions (country_code, level, name, parent_id, latitude, longitude, active)
SELECT ${esc(countryCode)}, 'country', ${esc(countryName)}, NULL::uuid, 21.5000000, -80.0000000, TRUE;

`;

const provinceList = provinces.map(p => {
  const [lat, lng] = latLng(p);
  return geoInsert('province', p, `(SELECT id FROM geo_regions WHERE level='country' AND country_code=${esc(countryCode)})`, lat, lng);
});
sql += `INSERT INTO geo_regions (country_code, level, name, parent_id, latitude, longitude, active)\n${provinceList.join('\nUNION ALL\n')};\n\n`;

for (const prov of provinces) {
  const muns = rows.filter(r => r.startsWith(prov + ',')).map(r => r.split(',')[1]);
  const munsList = muns.map(m => {
    const coords = municipalityCoords(m, prov);
    const subselect = `(SELECT id FROM geo_regions WHERE level='province' AND name=${esc(prov)} AND country_code=${esc(countryCode)})`;
    return geoInsert('municipality', m, subselect, coords?.[0] ?? null, coords?.[1] ?? null);
  });
  sql += `INSERT INTO geo_regions (country_code, level, name, parent_id, latitude, longitude, active)\n${munsList.join('\nUNION ALL\n')};\n\n`;
}

sql += `-- System setting for default country
INSERT INTO system_settings (key, value, value_type, is_public, description)
VALUES ('geo.default-country', ${esc(countryCode)}, 'string', true, 'Código ISO 3166-1 alpha-2 del país por defecto para direcciones')
ON CONFLICT (key) DO NOTHING;
`;

process.stdout.write(sql);
